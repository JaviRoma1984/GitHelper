  const total = () => SECTIONS.reduce((n, s) => n + s.items.length, 0);

  /** Filtra por texto (en el comando, la explicación o el título de la sección). Devuelve secciones nuevas con solo lo que coincide. */
  function filter(query) {
    const q = String(query || '').trim().toLowerCase();
    if (!q) return SECTIONS;
    const words = q.split(/\s+/);
    const out = [];
    SECTIONS.forEach((s) => {
      const title = s.title.toLowerCase();
      const items = s.items.filter((it) => {
        const hay = (it.c + ' ' + it.d + ' ' + (it.w || '') + ' ' + title).toLowerCase();
        return words.every((w) => hay.includes(w));
      });
      if (items.length) out.push({ id: s.id, icon: s.icon, title: s.title, items });
    });
    return out;
  }

  return { SECTIONS, total, filter };
